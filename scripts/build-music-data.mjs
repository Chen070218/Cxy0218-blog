// Builds XHBlogs/data/music.ts, the single source of truth for the music player.
//
// All tracks are royalty-free instrumentals from Pixabay Music. The audio files
// are committed under XHBlogs/public/music/pixabay/ so the player works offline
// on every host, with no key, no login and no external stream.
//
// Pixabay Content License: https://pixabay.com/service/license-summary/
//
// Usage: node scripts/build-music-data.mjs

import fs from 'fs';
import path from 'path';

const ROOT = path.resolve(import.meta.dirname, '..');
const OUT = path.join(ROOT, 'XHBlogs', 'data', 'music.ts');

const TRACKS = [
  {
    id: 'pixabay-ambient-dreams',
    slug: 'ambient-dreams',
    title: 'Ambient Dreams',
    artist: 'leberch',
    durationSec: 147,
  },
  {
    id: 'pixabay-nightlife',
    slug: 'nightlife',
    title: 'Nightlife',
    artist: 'Michael Kobrin',
    durationSec: 226,
  },
  {
    id: 'pixabay-cali',
    slug: 'cali',
    title: 'Cali',
    artist: 'Pixabay',
    durationSec: 181,
  },
  {
    id: 'pixabay-future-bass-atmospheric',
    slug: 'future-bass-atmospheric',
    title: 'Future Bass Atmospheric',
    artist: 'Pixabay',
    durationSec: 125,
  },
  {
    id: 'pixabay-minimal-technology',
    slug: 'minimal-technology',
    title: 'Minimal Technology',
    artist: 'Nastelbom',
    durationSec: 120,
  },
  {
    id: 'pixabay-snowlight',
    slug: 'snowlight',
    title: 'Snowlight',
    artist: 'Alanajordan',
    durationSec: 234,
  },
];

const tracks = TRACKS.map((track) => ({
  id: track.id,
  title: track.title,
  artist: track.artist,
  cover: `/music/covers/pixabay-${track.slug}.webp`,
  src: `/music/pixabay/${track.slug}.mp3`,
  kind: 'full',
  license: 'Pixabay Content License',
  licenseUrl: 'https://pixabay.com/service/license-summary/',
  sourceUrl: 'https://pixabay.com/music/',
  durationSec: track.durationSec,
}));

const file = [
  '// Generated by scripts/build-music-data.mjs — do not edit by hand.',
  '// All tracks: royalty-free Pixabay Music, hosted in public/music/pixabay.',
  '// License: Pixabay Content License (https://pixabay.com/service/license-summary/).',
  '',
  'export type MusicKind = "full" | "preview";',
  '',
  'export type MusicTrack = {',
  '  id: string;',
  '  title: string;',
  '  artist: string;',
  '  cover: string;',
  '  src: string;',
  '  kind: MusicKind;',
  '  license: string;',
  '  licenseUrl: string;',
  '  sourceUrl: string;',
  '  durationSec: number;',
  '};',
  '',
  'export const musicTracks: MusicTrack[] = [',
  ...tracks.map((track) => '  ' + JSON.stringify(track) + ','),
  '];',
  '',
].join('\n');

fs.writeFileSync(OUT, file, 'utf8');
console.log(`[ok] wrote ${tracks.length} Pixabay tracks to ${path.relative(ROOT, OUT)}`);
